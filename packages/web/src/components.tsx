export function ModeBadge({ mode }: { mode: string }) {
  const { t } = useI18n();
  const label =
    mode === "offline"
      ? t("mode_offline")
      : mode === "endpoint"
        ? t("mode_endpoint")
        : mode === "runtime"
          ? t("mode_runtime")
          : mode;
  return <span className={`badge mode-${mode}`}>{label}</span>;
}

export interface InstallCommandProps {
  owner: string;
  name: string;
  version?: string;
  supportedHarnesses?: string[];
}

interface HarnessOption {
  id: string;
  label: string;
  targetArg: string;
  icon: React.ReactNode;
}

const HARNESS_OPTIONS: HarnessOption[] = [
  { id: "agents", label: "Universal", targetArg: "agents", icon: <GlobeIcon size={14} /> },
  { id: "claude", label: "Claude Code", targetArg: "claude", icon: <ZapIcon size={14} /> },
  { id: "codex", label: "Codex", targetArg: "codex", icon: <CpuIcon size={14} /> },
  { id: "opencode", label: "OpenCode", targetArg: "opencode", icon: <TerminalIcon size={14} /> },
  { id: "openclaw", label: "OpenClaw", targetArg: "openclaw", icon: <LayersIcon size={14} /> },
  { id: "hermes", label: "Hermes", targetArg: "hermes", icon: <CompassIcon size={14} /> },
];

export function InstallCommand({
  owner,
  name,
  version,
  supportedHarnesses,
}: InstallCommandProps) {
  const { t } = useI18n();
  const [selectedHarness, setSelectedHarness] = useState<string>("agents");
  const [inProject, setInProject] = useState(false);
  const [copied, setCopied] = useState(false);
  const [ripple, setRipple] = useState(false);

  const activeOption =
    HARNESS_OPTIONS.find((h) => h.id === selectedHarness) ?? HARNESS_OPTIONS[0]!;

  const ref = version ? `${owner}/${name}@${version}` : `${owner}/${name}`;
  const targetFlag = `--target ${activeOption.targetArg}`;
  const projectFlag = inProject ? " --project" : "";
  const command = `npx @agentshare/cli install ${ref} ${targetFlag}${projectFlag}`;

  const copy = () => {
    void navigator.clipboard.writeText(command);
    setCopied(true);
    setRipple(true);
    setTimeout(() => setRipple(false), 500);
    setTimeout(() => setCopied(false), 2000);
  };

  return (
    <div className="install-box">
      <div className="install-tabs-header">
        <div className="install-tabs">
          {HARNESS_OPTIONS.map((opt) => {
            const isSupported =
              !supportedHarnesses ||
              supportedHarnesses.length === 0 ||
              supportedHarnesses.includes(opt.id) ||
              supportedHarnesses.includes("all") ||
              supportedHarnesses.includes("agents") ||
              opt.id === "agents";

            const displayLabel = opt.id === "agents" ? t("universalHarness") : opt.label;

            return (
              <button
                key={opt.id}
                type="button"
                className={`install-tab ${selectedHarness === opt.id ? "active" : ""} ${
                  !isSupported ? "untested" : ""
                }`}
                onClick={() => setSelectedHarness(opt.id)}
              >
                <span className="tab-icon">{opt.icon}</span>
                <span className="tab-label">{displayLabel}</span>
                {!isSupported && <span className="tab-pill">{t("unverifiedPill")}</span>}
              </button>
            );
          })}
        </div>

        <label className="project-checkbox" title={t("projectCheckboxTitle")}>
          <input
            type="checkbox"
            checked={inProject}
            onChange={(e) => setInProject(e.target.checked)}
          />
          <span>{t("projectCheckboxLabel")}</span>
        </label>
      </div>

      <div className={`install-code-bar ${ripple ? "ripple" : ""}`}>
        <span className="prompt-glyph">$</span>
        <code className="install-code">{command}</code>
        <button
          type="button"
          className={`install-copy-btn ${copied ? "copied" : ""}`}
          onClick={copy}
        >
          {copied ? (
            <>
              <CheckIcon size={15} />
              <span>{t("copiedBtn")}</span>
            </>
          ) : (
            <>
              <svg width="15" height="15" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2" strokeLinecap="round" strokeLinejoin="round" aria-hidden="true"><rect x="9" y="9" width="13" height="13" rx="2" ry="2"/><path d="M5 15H4a2 2 0 0 1-2-2V4a2 2 0 0 1 2-2h9a2 2 0 0 1 2 2v1"/></svg>
              <span>{t("copyBtn")}</span>
            </>
          )}
        </button>
      </div>
    </div>
  );
}

export function PackCard({ pack }: { pack: PackSummary }) {
  const { t, td } = useI18n();
  return (
    <a className="card" href={`#/agents/${pack.owner}/${pack.name}`}>
      <div className="card-head">
        <span className="ref">
          {pack.owner}/{pack.name}
        </span>
        <ModeBadge mode={pack.mode} />
      </div>
      <h3>{td(pack.title)}</h3>
      <p>{td(pack.description)}</p>
      <div className="card-tags">
        {(pack.tags ?? []).slice(0, 3).map((tag) => (
          <span key={tag} className="tag-pill">
            #{td(tag)}
          </span>
        ))}
      </div>
      <div className="card-foot">
        <span className="version-tag">v{pack.version}</span>
        <span className="stats-tag">
          <StarIcon size={12} filled />
          <span>{pack.stars} · {pack.downloads} {t("downloadsSuffix")}</span>
        </span>
      </div>
    </a>
  );
}

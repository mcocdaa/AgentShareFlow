export function getAvatarMeta(handle: string): { initials: string; tone: number } {
  const cleaned = handle.trim().replace(/^@/, "");
  const parts = cleaned.split(/[-_\s]+/).filter(Boolean);
  let initials = "AG";
  if (parts.length >= 2) {
    const first = parts[0] ?? "";
    const last = parts[parts.length - 1] ?? "";
    if (/^\d+$/.test(last)) {
      initials = `${first.slice(0, 1)}${last.slice(-1)}`.toUpperCase();
    } else {
      initials = `${first.slice(0, 1)}${(parts[1] ?? "").slice(0, 1)}`.toUpperCase();
    }
  } else if (cleaned.length > 0) {
    initials = cleaned.slice(0, 2).toUpperCase();
  }

  let hash = 0;
  for (let i = 0; i < cleaned.length; i += 1) {
    hash = (hash * 31 + cleaned.charCodeAt(i)) >>> 0;
  }
  return { initials, tone: hash % 6 };
}
